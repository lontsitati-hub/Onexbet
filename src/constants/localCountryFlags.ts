export function getLocalCountryFlag(code: string | null | undefined): any | null {
  const key = String(code || '').trim().toLowerCase();
  const aliases: Record<string, string> = {
    england: 'gb-eng',
    scotland: 'gb-sct',
    wales: 'gb-wls',
    'northern ireland': 'gb-nir',
  };
  return LOCAL_COUNTRY_FLAGS[aliases[key] || key] || null;
}

export function getOfficialCountryName(code: string | null | undefined): string | null {
  const key = String(code || '').trim().toUpperCase();
  return LOCAL_COUNTRY_NAMES[key.toLowerCase()] || null;
}
